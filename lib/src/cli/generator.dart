import 'dart:convert';

import 'answers.dart';

/// A Dart string literal for [value].
String _q(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$');
  return "'$escaped'";
}

/// The `lib/app_update.dart` file the wizard writes.
String appUpdateSource(SetupAnswers a) {
  final keys = switch (a.keyStyle) {
    KeyStyle.standard => '',
    KeyStyle.prefixed => '    keys: const UpdateKeys.prefixed(${_q(a.prefix)}),\n',
    KeyStyle.nested => '    keys: const UpdateKeys.nested(),\n',
  };
  final changes = a.source == ConfigSource.firebase
      ? '    subscribeToChanges: true,\n'
      : '';
  return '''
// Generated by `dart run adaptable_remote_config`. Safe to edit.
import 'package:adaptable_remote_config/adaptable_remote_config.dart';

/// Remote-controlled app updates. Pass [controller] to `UpdateGate`.
class AppUpdate {
  AppUpdate._();

  /// Created on first use, so initialize Firebase (if used) before reading it.
  static final RemoteConfigController controller = RemoteConfigController(
    appId: ${_q(a.appId)},
${_provider(a)}$keys$changes  );
}
''';
}

String _provider(SetupAnswers a) => switch (a.source) {
  ConfigSource.firebase => '''
    provider: FirebaseConfigProvider(
      // Replaces any defaults set elsewhere: list every key the app reads.
      defaults: const {
${_defaults(a)}      },
    ),
''',
  ConfigSource.http =>
    '    provider: HttpConfigProvider(url: Uri.parse(${_q(a.httpUrl)})),\n',
  ConfigSource.custom => '''
    provider: CustomConfigProvider(() async {
      // TODO: load your remote values (an API call, a database...) and return
      // them as a map. These are the keys the app reads:
${_defaults(a, indent: '      //   ')}      return {};
    }),
''',
};

/// `'key': value,` lines for each value, used as Firebase defaults.
String _defaults(SetupAnswers a, {String indent = '        '}) {
  final lines = StringBuffer();
  for (final spec in a.parameters) {
    final value = spec.type == 'Boolean' ? spec.example : _q(spec.example);
    lines.writeln('$indent${_q(spec.name)}: $value,');
  }
  return lines.toString();
}

/// What to create in the Firebase console, or the JSON to host.
String remoteValuesGuide(SetupAnswers a) => switch (a.source) {
  ConfigSource.firebase => _firebaseGuide(a),
  ConfigSource.http => _jsonGuide(a),
  ConfigSource.custom => _customGuide(a),
};

String _firebaseGuide(SetupAnswers a) {
  final b = StringBuffer(
    'Firebase console > Remote Config > Add parameter, for each of:\n\n',
  );
  if (a.group.isNotEmpty) {
    b.writeln(
      'Tip: put them in a folder called "${a.group}" '
      '(Add new > Parameter group), so each app has its own folder.\n',
    );
  }
  for (final spec in a.parameters) {
    final example = spec.example.isEmpty ? '(empty)' : spec.example;
    b.writeln('  ${spec.name}  [${spec.type}]  e.g. $example');
    b.writeln('      ${spec.meaning}');
  }
  b.writeln('\nThen press "Publish changes".');
  return b.toString();
}

String _jsonGuide(SetupAnswers a) {
  final root = <String, Object?>{};
  for (final spec in a.parameters) {
    final value = spec.type == 'Boolean' ? spec.example == 'true' : spec.example;
    _setPath(root, spec.name, value);
  }
  final json = const JsonEncoder.withIndent('  ').convert(root);
  return 'Host this JSON at ${a.httpUrl}:\n\n$json\n';
}

String _customGuide(SetupAnswers a) {
  final b = StringBuffer('Your loader returns a map with these keys:\n\n');
  for (final spec in a.parameters) {
    b.writeln('  ${spec.name}  [${spec.type}]  ${spec.meaning}');
  }
  return b.toString();
}

void _setPath(Map<String, Object?> root, String path, Object? value) {
  final parts = path.split('.');
  var node = root;
  for (final part in parts.take(parts.length - 1)) {
    node = node.putIfAbsent(part, () => <String, Object?>{})
        as Map<String, Object?>;
  }
  node[parts.last] = value;
}

/// The edits the wizard could not make itself. Empty when nothing is left.
String nextSteps(
  SetupAnswers a, {
  required String importPath,
  bool firebaseDone = false,
  bool gateDone = false,
}) {
  final b = StringBuffer();
  final firebase = a.source == ConfigSource.firebase && !firebaseDone;
  if (firebase) {
    b.writeln('''
Initialize Firebase in lib/main.dart (run `flutterfire configure` once):

  void main() async {
    WidgetsFlutterBinding.ensureInitialized();
    await Firebase.initializeApp();
    runApp(const MyApp());
  }
''');
  }
  if (!gateDone) {
    final optional = a.usesOptional ? '' : '\n      showOptional: false,';
    b.writeln('''
Wrap the app, above every route (add: import '$importPath'):

  MaterialApp(            // or MaterialApp.router(
    builder: (context, child) => UpdateGate(
      controller: AppUpdate.controller,$optional
      child: child!,
    ),
    ...
  )
''');
  }
  return b.toString();
}
